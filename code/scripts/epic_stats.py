"""EPIC-KITCHENS-100 annotation statistics -> docs/EPIC_STATS.md (+ JSON of raw numbers).

Usage: python code/scripts/epic_stats.py [ann_dir] [out_md]
Reads only the public annotation CSVs (no videos).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd


def ts(s: pd.Series) -> pd.Series:
    t = pd.to_timedelta(s)
    return t.dt.total_seconds()


def q(x, ps=(5, 25, 50, 75, 95, 99)):
    x = np.asarray(x, float)
    return {f"p{p}": float(np.percentile(x, p)) for p in ps} | {
        "mean": float(x.mean()), "min": float(x.min()), "max": float(x.max())}


def fmt_q(d, nd=2):
    return " / ".join(f"{d[k]:.{nd}f}" for k in ("min", "p5", "p25", "p50", "p75", "p95", "max"))


def coverage(df_eval: pd.DataFrame, predicted_pairs_per_video: dict) -> float:
    """Mean over videos of |GT pairs ∩ predicted pairs| / |GT pairs| (label-only variant)."""
    vals = []
    for vid, g in df_eval.groupby("video_id"):
        gt = set(zip(g.verb, g.noun))
        pr = predicted_pairs_per_video.get(vid, set())
        vals.append(len(gt & pr) / len(gt))
    return float(np.mean(vals))


def main(ann_dir="data/epic_annotations", out_md="docs/EPIC_STATS.md"):
    ann = Path(ann_dir)
    tr = pd.read_csv(ann / "EPIC_100_train.csv")
    va = pd.read_csv(ann / "EPIC_100_validation.csv")
    info = pd.read_csv(ann / "EPIC_100_video_info.csv")
    vcls = pd.read_csv(ann / "EPIC_100_verb_classes.csv")
    ncls = pd.read_csv(ann / "EPIC_100_noun_classes.csv")
    # Use class keys (canonical names) rather than free-text verbs/nouns.
    vkey = dict(zip(vcls.id, vcls.key))
    nkey = dict(zip(ncls.id, ncls.key))
    for d in (tr, va):
        d["verb"] = d.verb_class.map(vkey)
        d["noun"] = d.noun_class.map(nkey)
        d["start"] = ts(d.start_timestamp)
        d["end"] = ts(d.stop_timestamp)
        d["dur"] = d.end - d.start
        d["pair"] = d.verb + "|" + d.noun
    dur_map = dict(zip(info.video_id, info.duration))
    fps_map = dict(zip(info.video_id, info.fps))
    R: dict = {}
    L: list[str] = []
    w = L.append

    w("# EPIC-KITCHENS-100 annotation statistics\n")
    w("Generated by `code/scripts/epic_stats.py` from the public annotation CSVs "
      "(github.com/epic-kitchens/epic-kitchens-100-annotations). Verbs/nouns use the "
      "canonical class keys (97 verb / 300 noun classes), not free-text narrations.\n")
    w("> These are EPIC-100 statistics, not the Track 4 kit. The kit's "
      "`supported_classes.json` may use a different vocabulary or pair list.\n")

    # --- Overview ---
    w("## 1. Overview\n")
    w("| | train | validation |\n|---|---:|---:|")
    for name, f in [("segments", len), ("videos", lambda d: d.video_id.nunique()),
                    ("participants", lambda d: d.participant_id.nunique()),
                    ("distinct verbs", lambda d: d.verb.nunique()),
                    ("distinct nouns", lambda d: d.noun.nunique()),
                    ("distinct verb–noun pairs", lambda d: d.pair.nunique())]:
        w(f"| {name} | {f(tr):,} | {f(va):,} |")
    R["n_segments"] = {"train": len(tr), "val": len(va)}
    vdur_tr = np.array([dur_map[v] for v in tr.video_id.unique()])
    vdur_va = np.array([dur_map[v] for v in va.video_id.unique()])
    w("")
    w("## 2. Video durations (seconds)\n")
    w("min / p5 / p25 / median / p75 / p95 / max\n")
    w(f"- train: {fmt_q(q(vdur_tr), 0)}  (total {vdur_tr.sum()/3600:.1f} h)")
    w(f"- validation: {fmt_q(q(vdur_va), 0)}  (total {vdur_va.sum()/3600:.1f} h)")
    in_rng = ((vdur_va >= 120) & (vdur_va <= 600)).mean()
    w(f"- validation videos inside the Track 4 2–10 min range: **{in_rng:.0%}** "
      f"({int(in_rng*len(vdur_va))}/{len(vdur_va)}). Under 2 min: "
      f"{(vdur_va<120).mean():.0%}; over 10 min: {(vdur_va>600).mean():.0%}.")
    fps_va = pd.Series([fps_map[v] for v in va.video_id.unique()]).round(2).value_counts()
    w(f"- validation fps values: { {float(k): int(v) for k, v in fps_va.items()} }\n")
    R["val_video_duration"] = q(vdur_va)
    R["val_in_2_10min"] = float(in_rng)

    # --- Long tail ---
    w("## 3. Class frequency and long tail (train)\n")
    for col in ("verb", "noun", "pair"):
        c = tr[col].value_counts()
        cum = c.cumsum() / c.sum()
        k50, k80, k90, k95 = (int((cum < p).sum()) + 1 for p in (.5, .8, .9, .95))
        lt10 = int((c < 10).sum())
        w(f"**{col}s** ({len(c)} classes): top-{k50} cover 50% of segments, top-{k80} 80%, "
          f"top-{k90} 90%, top-{k95} 95%. Classes with <10 train segments: {lt10} "
          f"({lt10/len(c):.0%}). Max/median count: {c.max():,} / {int(c.median())}.\n")
        R[f"{col}_tail"] = {"n": len(c), "k50": k50, "k80": k80, "k90": k90, "k95": k95,
                            "lt10": lt10}
    w("Top 15 verbs: " + ", ".join(f"{k} ({v:,})" for k, v in
                                   tr.verb.value_counts().head(15).items()) + "\n")
    w("Top 15 nouns: " + ", ".join(f"{k} ({v:,})" for k, v in
                                   tr.noun.value_counts().head(15).items()) + "\n")
    w("Top 20 pairs: " + ", ".join(f"{k.replace('|', ' ')} ({v:,})" for k, v in
                                   tr.pair.value_counts().head(20).items()) + "\n")

    # --- Co-occurrence ---
    w("## 4. Verb–noun co-occurrence (train)\n")
    possible = tr.verb.nunique() * tr.noun.nunique()
    w(f"- Observed pairs: {tr.pair.nunique():,} of {possible:,} possible verb×noun "
      f"combinations ({tr.pair.nunique()/possible:.1%}). The co-occurrence matrix is very "
      "sparse, so a pair prior from train counts strongly constrains fusion.")
    npv = tr.groupby("verb").noun.nunique()
    vpn = tr.groupby("noun").verb.nunique()
    w(f"- Nouns per verb: median {int(npv.median())}, max {npv.max()} ({npv.idxmax()}).")
    w(f"- Verbs per noun: median {int(vpn.median())}, max {vpn.max()} ({vpn.idxmax()}).")
    # conditional entropy
    def cond_ent(a, b):
        ct = pd.crosstab(tr[a], tr[b]).values.astype(float)
        p = ct / ct.sum()
        pa = p.sum(1, keepdims=True)
        with np.errstate(divide="ignore", invalid="ignore"):
            h = -np.nansum(p * np.log2(np.where(p > 0, p / pa, 1)))
        return h
    hn = -(tr.noun.value_counts(normalize=True).pipe(lambda s: (s*np.log2(s)).sum()))
    hv = -(tr.verb.value_counts(normalize=True).pipe(lambda s: (s*np.log2(s)).sum()))
    w(f"- Entropy H(noun)={hn:.2f} bits, H(noun|verb)={cond_ent('verb','noun'):.2f}; "
      f"H(verb)={hv:.2f}, H(verb|noun)={cond_ent('noun','verb'):.2f}. Knowing the noun "
      "removes more uncertainty about the verb than the reverse.")
    vp = set(va.pair)
    unseen = vp - set(tr.pair)
    seg_unseen = va.pair.isin(unseen).mean()
    w(f"- Validation pairs never seen in train: {len(unseen)} of {len(vp)} distinct pairs "
      f"({len(unseen)/len(vp):.0%}), covering {seg_unseen:.1%} of validation segments. "
      "A detector restricted to train-seen pairs cannot get these.\n")
    R["val_unseen_pairs"] = {"n": len(unseen), "of": len(vp), "seg_frac": float(seg_unseen)}

    # --- Durations ---
    w("## 5. Action segment durations (seconds)\n")
    w("min / p5 / p25 / median / p75 / p95 / max\n")
    w(f"- train: {fmt_q(q(tr.dur))}")
    w(f"- validation: {fmt_q(q(va.dur))}")
    for thr in (0.5, 1, 2, 5, 10):
        w(f"  - share of train segments shorter than {thr}s: {(tr.dur < thr).mean():.1%}")
    vmed = tr.groupby("verb").dur.median().sort_values()
    w(f"- Shortest median-duration verbs: " + ", ".join(
        f"{k} {v:.1f}s" for k, v in vmed.head(6).items()))
    w(f"- Longest median-duration verbs: " + ", ".join(
        f"{k} {v:.1f}s" for k, v in vmed.tail(6).items()) + "\n")
    R["seg_dur_train"] = q(tr.dur)

    # --- Density ---
    w("## 6. Action density\n")
    def density(d):
        g = d.groupby("video_id")
        apm = g.size() / (g.video_id.first().map(dur_map) / 60)
        dp = g.pair.nunique()
        dpm = dp / (g.video_id.first().map(dur_map) / 60)
        return apm, dp, dpm
    for name, d in (("train", tr), ("validation", va)):
        apm, dp, dpm = density(d)
        w(f"- {name}: actions/min {fmt_q(q(apm),1)}; distinct pairs/video "
          f"{fmt_q(q(dp),0)}; distinct pairs/min {fmt_q(q(dpm),1)}")
    _, dp_va, _ = density(va)
    R["val_distinct_pairs_per_video"] = q(dp_va)
    # overlap/concurrency
    def overlap_frac(d):
        fr = []
        for _, g in d.sort_values("start").groupby("video_id"):
            s, e = g.start.values, g.end.values
            run_end = np.maximum.accumulate(e)
            fr.append(np.mean(s[1:] < run_end[:-1]) if len(s) > 1 else 0)
        return float(np.mean(fr))
    w(f"- Share of segments that start before the previous one ends (overlapping actions): "
      f"train {overlap_frac(tr):.0%}, validation {overlap_frac(va):.0%}.")
    # how much of a video is covered by any action
    def covered(d):
        out = []
        for vid, g in d.groupby("video_id"):
            D = dur_map[vid]
            m = np.zeros(int(D * 10) + 1, bool)
            for s, e in zip(g.start, g.end):
                m[int(s*10):int(e*10)+1] = True
            out.append(m.mean())
        return np.array(out)
    cv = covered(va)
    w(f"- Fraction of each validation video covered by at least one action: "
      f"median {np.median(cv):.0%} (p5 {np.percentile(cv,5):.0%}, p95 "
      f"{np.percentile(cv,95):.0%}). Idle footage is the rest.\n")

    # --- Pair repetition within a video ---
    w("## 7. Repetition within a video\n")
    rep = va.groupby(["video_id", "pair"]).size()
    w(f"- Validation: each distinct (video, pair) occurs {rep.mean():.2f} times on average "
      f"(median {int(rep.median())}, p95 {int(np.percentile(rep,95))}). Coverage rewards one "
      "hit per distinct pair, so repeated instances add nothing to coverage (they matter only "
      "for mAP).\n")

    # --- Coverage reference points ---
    w("## 8. Coverage reference points (label-only variant, validation)\n")
    w("Coverage = mean over videos of |GT pairs ∩ predicted pairs| / |GT pairs|. These are "
      "**priors-only references** computed from annotations (no video model), useful to "
      "judge how much a model adds. They ignore timing; the tIoU≥0.1 variant would be lower.\n")
    w("| Strategy | K pairs/video | coverage |\n|---|---:|---:|")
    top = list(tr.pair.value_counts().index)
    vids = va.video_id.unique()
    for K in (10, 25, 50, 100, 200):
        cov = coverage(va.assign(p=va.pair), {v: {tuple(p.split("|")) for p in top[:K]}
                                              for v in vids})
        w(f"| same K most frequent train pairs for every video | {K} | {cov:.1%} |")
        R[f"cov_topk_{K}"] = cov
    # oracle on nouns: if we knew which nouns appear, predict top verbs for each
    for kv in (1, 3, 5):
        top_v_per_n = tr.groupby("noun").verb.agg(lambda s: list(s.value_counts().index[:kv]))
        pr = {}
        for vid, g in va.groupby("video_id"):
            pr[vid] = {(v, n) for n in set(g.noun) for v in top_v_per_n.get(n, [])}
        cov = coverage(va, pr)
        npred = np.mean([len(p) for p in pr.values()])
        w(f"| oracle nouns-in-video × top-{kv} train verbs per noun | ~{npred:.0f} | {cov:.1%} |")
        R[f"cov_oracle_noun_top{kv}v"] = cov
    w("\nReading: the noun-oracle rows show that **recognising which objects appear** in a "
      "video, combined with a verb prior per noun, already explains most of the coverage; "
      "noun recognition is the main lever for the 40% coverage metric.\n")

    # --- Implications ---
    w("## 9. Implications for the coverage strategy (to confirm once the kit arrives)\n")
    w("1. Output many diverse pairs per video. Distinct GT pairs per val video has median "
      f"{int(dp_va.median())}, so K must be well above that if precision allows (decided by "
      "whether actions carry a confidence score in the kit schema).")
    w("2. Use a train co-occurrence prior to restrict and rank verb–noun fusions; the matrix "
      "is sparse, so the prior removes most impossible pairs.")
    w("3. Segments are short (median ~" f"{np.median(tr.dur):.1f} s) and often overlap; the "
      "localisation stride must be ≤1 s, and NMS must allow overlapping different pairs.")
    w("4. Long tail: a small number of verbs dominate; use focal loss / balanced sampling and "
      "report per-frequency-bucket recall.")
    w("5. Video-length mismatch: many EPIC val videos are outside 2–10 min (section 2); check "
      "whether the kit clips them.")
    Path(out_md).parent.mkdir(parents=True, exist_ok=True)
    Path(out_md).write_text("\n".join(L), encoding="utf-8")
    Path(out_md).with_suffix(".json").write_text(json.dumps(R, indent=2, default=float))
    print(f"wrote {out_md}", file=sys.stderr)


if __name__ == "__main__":
    main(*sys.argv[1:])
